;;; version <-> version-map

(defn- maybe-read [s]
  (try
    (edn/read-string s)
    (catch Exception _
      s)))

(defn- interpolate
  "Replace placeholders of form {{key}} in template string with values from map.

   Example:
   (interpolate \"version {{major}}.{{minor}}\" {:major 1 :minor 2})
   => \"version 1.2\""
  [template data]
  (reduce-kv
   (fn [s k v]
     (str/replace s (format "{{%s}}" (name k)) (str v)))
   template
   data))

(defn version->version-map
  [version]
  {:pre [(string? version)]}
  (let [components (into [] (str/split version #"[.]"))
        [non-q q]  (str/split (last components) #"-")
        components (into (pop components) [non-q q])]
    (zipmap
     [:major :minor :incremental :qualifier]
     (mapv maybe-read components))))

(defn version-map->version
  [version-map]
  {:pre  [(map? version-map)]
   :post [string?]}
  (let [components (keep version-map [:major :minor :incremental])
        q          (:qualifier version-map)]
    (cond-> (str/join "." components)
      q (str "-" q))))

;;; Version Expansion


(defmulti expand-component
  (fn [component] component))

(defmethod expand-component :default
  [component] component)

(defmethod expand-component :git-rev-count
  [_component] (edn/read-string (b/git-count-revs nil)))

(def ^:private formatter
  (java.time.format.DateTimeFormatter/ofPattern "YYYY.MM.dd"))

(defmethod expand-component :reverse-date
  [_component]
  (.format formatter (java.time.LocalDate/now)))

(defn interpolate-version [s]
  (interpolate
   s
   {:git-rev-count (b/git-count-revs nil)
    :reverse-date  (.format formatter (java.time.LocalDate/now))}))

(defn expand-version-map
  [version-map]
  (prn :version-map version-map)
  (reduce-kv
   (fn [vm k value]
     (assoc vm k (expand-component value)))
   {}
   version-map))

(defn expand-version [params]
  (let [version (-> (:version params)
                    interpolate-version
                    version->version-map
                    version-map->version)]
    (assoc params :version version)))

;;; File Handling

(defn project-edn-path
  ^java.nio.file.Path [{:keys [project-root]}]
  (fs/path (or project-root ".") "project.edn"))

(def template-project-edn "{:name noname\n :version \"\"}")

(defn- validate-data!
  [{:keys [version name] :as data} f]
  (when-not version
    (throw (ex-info "project.edn must contain :version" {:path (str f)})))
  (when-not name
    (throw (ex-info "project.edn must contain :name" {:path (str f)})))
  data)

(defn load-project
  [params]
  (let [f (-> params project-edn-path fs/file)]
    (merge (-> f
               slurp
               edn/read-string
               (validate-data! f))
           params)))

(defn update-version
  [{:keys [name version]} src]
  (-> (z/of-string src)
      (z/subedit->
       (z/get :name)
       (z/replace name))
      (z/subedit->
       (z/get :version)
       (z/replace version))
      z/root-string))

(defn project-data
  "Read and expand project.edn"
  [params]
  (v/println "Reading project data")
  (-> params
      load-project
      defaults/project-data
      expand-version))

#_(defn write-version
    "Write the current project version to project.edn."
    [params]
    (v/println "Writing version to project data" (:version params))
    (write params))

#_(defn write-version-file
    "Write the current project version to a file with an edn map.
  By default writes to version.edn."
    [params]
    (v/println "Writing version file" (:version params))
    (write-version-file params))

#_(defn read-version-file
    "Read the project version from a file with an edn map.
  By default writes to version.edn."
    [params]
    (v/println "Reading version file")
    (read-version-file params))

;;; Read and write version files

(defn version-file-path
  [{:keys [dir path] :or {dir "." path "version.edn"} :as _params}]
  (if (fs/relative? path)
    (fs/file dir path)
    path))

(defn write-version-file
  [params]
  (let [path (version-file-path params)]
    (spit
     path
     (str
      ";; Generated by makejack write-version\n"
      (pr-str (select-keys params [:version])))))
  params)

(defn read-version-file
  [params]
  (let [path              (version-file-path params)
        {:keys [version]} (edn/read-string (slurp path))]
    (assoc params :version version)))
